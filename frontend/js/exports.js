/* ===== CSV / Excel export ===== */
function downloadCSV(filename, headers, rows){
  const esc=v=>{v=(v==null?'':String(v)).replace(/"/g,'""');return /[",\n]/.test(v)?'"'+v+'"':v;};
  const csv=[headers.map(esc).join(',')].concat(rows.map(r=>r.map(esc).join(','))).join('\n');
  const blob=new Blob(['\ufeff'+csv],{type:'text/csv;charset=utf-8;'});
  const url=URL.createObjectURL(blob);const a=document.createElement('a');
  a.href=url;a.download=filename;document.body.appendChild(a);a.click();
  document.body.removeChild(a);URL.revokeObjectURL(url);
}
// Excel-compatible: CSV opens directly in Excel; also offer .xls via HTML table
function downloadXLS(filename, headers, rows){
  let h='<table><tr>'+headers.map(c=>'<th>'+c+'</th>').join('')+'</tr>';
  h+=rows.map(r=>'<tr>'+r.map(c=>'<td>'+(c==null?'':String(c))+'</td>').join('')+'</tr>').join('');
  h+='</table>';
  const blob=new Blob(['<html xmlns:x="urn:schemas-microsoft-com:office:excel"><head><meta charset="utf-8"></head><body>'+h+'</body></html>'],
    {type:'application/vnd.ms-excel'});
  const url=URL.createObjectURL(blob);const a=document.createElement('a');
  a.href=url;a.download=filename;document.body.appendChild(a);a.click();
  document.body.removeChild(a);URL.revokeObjectURL(url);
}
// export buttons markup (CSV + Excel) wired by data attributes
let __exportRegistry={};
// [2.0] export buttons are only shown to roles with the export:run permission (enforced server-side too)
function exportBtns(id){if(!API.can('export:run'))return '';return `<span class="exp"><button class="xbtn" onclick="runExport('${id}','csv')">⬇ CSV</button><button class="xbtn" onclick="runExport('${id}','xls')">⬇ Excel</button></span>`;}
function registerExport(id,filename,headers,rowsFn){__exportRegistry[id]={filename,headers,rowsFn};}
function runExport(id,kind){
  // [2.0] the cost-mapping table is paginated server-side, so its export is generated by the API (full result set)
  if(id==='cmTable'){API.download('/exports/cost-mapping',{...filterParams(),format:kind==='csv'?'csv':'xlsx',q:_cmState.q,cat:_cmState.cat,
      sort:CM_KEYS[_cmState.sortK],dir:_cmState.sortDir>0?'asc':'desc'},'MEDD_cost_mapping.'+(kind==='csv'?'csv':'xlsx')).catch(e=>showError(e.message));return;}
  const e=__exportRegistry[id];if(!e)return;const rows=e.rowsFn();
  if(kind==='csv')downloadCSV(e.filename+'.csv',e.headers,rows);else downloadXLS(e.filename+'.xls',e.headers,rows);}
